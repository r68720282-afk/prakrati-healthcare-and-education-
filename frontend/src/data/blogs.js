export const getBlogBySlug = (slug) => blogs.find((blog) => blog.slug === slug);

export const getRelatedBlogs = (currentBlog, limit = 3) =>
  blogs
    .filter((blog) => blog.slug !== currentBlog.slug && blog.category === currentBlog.category)
    .concat(blogs.filter((blog) => blog.slug !== currentBlog.slug))
    .filter((blog, index, self) => index === self.findIndex((item) => item.slug === blog.slug))
    .slice(0, limit);
